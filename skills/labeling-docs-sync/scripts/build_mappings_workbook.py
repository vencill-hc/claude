HEADER_FONT = Font(bold=True)
WRAP = Alignment(wrap_text=True, vertical="top")


def _git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True).stdout.strip()


def add_table(ws, start_row: int, headers: list[str], rows: list[list[str]], widths: list[int]) -> int:
    for c, h in enumerate(headers, 1):
        cell = ws.cell(row=start_row, column=c, value=h)
        cell.font = HEADER_FONT
    for r, row in enumerate(rows, start_row + 1):
        for c, v in enumerate(row, 1):
            ws.cell(row=r, column=c, value=v).alignment = WRAP
    for c, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(c)].width = w
    return start_row + 1 + len(rows)


def intro(ws, text: str) -> int:
    ws.cell(row=1, column=1, value=text).alignment = WRAP
    ws.row_dimensions[1].height = 60
    return 3


