def build(out_path: str) -> None:
    version = f"{_git('rev-parse', '--short', 'HEAD')} ({_git('log', '-1', '--format=%ad', '--date=short')})"
    drift = _git("diff", "--stat", "HEAD", "origin/main", "--",
                 "src/utils/seniority_utils.py", "src/utils/employment_utils.py",
                 "src/utils/string_validator_utils.py", "src/constants/industry_mappings.py",
                 "src/data_types/person_types.py", "src/data_types/organization_types.py",
                 "src/pipelines/label/people/person_highlights_transforms.py")
    if drift:
        print(f"WARNING: checkout differs from origin/main for source files:\n{drift}")

    wb = Workbook()

    # --- About ---
    ws = wb.active
    ws.title = "About"
    rows = [
        ["What this is", "How GDU turns raw data (job titles, funding events, source industries) into the standardized fields you see in search: industry, job function, seniority, career highlights, and funding stage."],
        ["Generated from code version", version],
        ["How to read it", "Each tab covers one derived field. Tabs are generated directly from the production rules, so what you read here is exactly what the system does."],
        ["Questions / corrections", "Comment on the sheet or reach out to the Data Universe team."],
    ]
    add_table(ws, 1, ["", ""], rows, [28, 120])

    # --- Industry Mapping ---
    ws = wb.create_sheet("Industry Mapping")
    r = intro(ws, "Source industries from Crunchbase and LinkedIn mapped to GDU's standardized industry taxonomy. One source industry can map to multiple GDU industries for comprehensiveness.")
    ind_rows = []
    for source, mapping in [("Crunchbase", CRUNCHBASE_TO_UNIVERSE_INDUSTRIES),
                            ("Crunchbase (Investor)", CRUNCHBASE_INVESTOR_TO_UNIVERSE_INDUSTRIES),
                            ("LinkedIn", LINKEDIN_TO_UNIVERSE_INDUSTRIES)]:
        for src_industry in sorted(mapping):
            for gdu in mapping[src_industry]:
                ind_rows.append([source, src_industry, gdu.value if hasattr(gdu, "value") else str(gdu)])
    add_table(ws, r, ["Data Source", "Source Industry", "GDU Industry"], ind_rows, [22, 40, 40])
    print(f"Industry rows: {len(ind_rows)}")

    # --- Job Function Mapping ---
    ws = wb.create_sheet("Job Function Mapping")
    r = intro(ws, "GDU derives a person's job function by scanning their job title for the keywords below, in the order listed — the first keyword found decides the function. A keyword marked BLOCKER stops the scan with no function assigned.")
    jf_rows = []
    for i, (kw, fn) in enumerate(JOB_FUNCTION_TITLE_COMPONENTS.items(), 1):
        jf_rows.append([i, kw, fn.value if fn is not None else "(BLOCKER — no function assigned)"])
    regex_note_row = r
    add_table(ws, r, ["Priority (matched in this order)", "Keyword in Job Title", "Assigned Job Function"], jf_rows, [16, 40, 40])
    print(f"Job function keyword rows: {len(jf_rows)} (+{len(JOB_FUNCTION_TITLE_COMPONENTS_REGEXES)} regex components)")

    # --- Seniority Mapping ---
    ws = wb.create_sheet("Seniority Mapping")
    r = intro(ws, "GDU derives a person's seniority level from their job title in three steps: normalize the title, find every keyword it contains, then resolve the matches to a single level.")
    ws.cell(row=r, column=1, value="Step 1 — Normalize the title").font = HEADER_FONT
    r += 1
    ws.cell(row=r, column=1, value="The title is lowercased, punctuation is stripped (hyphens/slashes become spaces, 'and' becomes '&'), and equivalent spellings and abbreviations are unified so each concept matches one keyword:").alignment = WRAP
    r += 1
    syn_rows = [[k, v] for k, v in JOB_TITLE_NORMALIZATION_SYNONYMS.items()]
    r = add_table(ws, r, ["Written in the title as...", "Treated as"], syn_rows, [45, 45]) + 1

    ws.cell(row=r, column=1, value="Step 2 — Find every keyword").font = HEADER_FONT
    r += 1
    ws.cell(row=r, column=1, value="Every keyword below that appears in the title is collected (a title can match several). A more specific phrase always takes priority over the generic word inside it.").alignment = WRAP
    r += 2
    ladder_order = sorted(sen._LADDER, key=lambda lvl: -sen._LADDER[lvl])
    lex_rows = []
    for level in ladder_order:
        entries = [e for e in sen._LEXICON if (sen.JobSeniority.LEVEL_SENIOR if e.kind is sen._Kind.UPLIFT else e.seniority) is level]
        if not entries:
            continue
        for e in entries:
            raw_kw = " ".join(e.tokens)
            display = TOKEN_DISPLAY.get(raw_kw, raw_kw)
            lex_rows.append([display, level.value, SENIORITY_NOTES.get(raw_kw, "")])
    r = add_table(ws, r, ["Keyword", "Seniority Level", "Notes"], lex_rows, [40, 22, 100]) + 1

    disq = sorted(sen._BOARD_DISQUALIFIER_TOKENS) + [" ".join(b) for b in sen._BOARD_DISQUALIFIER_BIGRAMS]
    r = add_table(ws, r, ["Board disqualifier words (no level of their own)", "", ""],
                  [[d, "", "A title containing this plus a board keyword is Entry (Guest Board Member -> Entry)"] for d in disq], [40, 22, 100]) + 1

    from utils.board_seat_utils import _EXCLUDED_BOARD_PATTERNS, _NORMALIZE_SUBS as BOARD_SUBS, _Token as BToken  # noqa: E402
    excl_display = ["former", "past", "emeritus", "trustee emeritus", "board secretary", "board certified", "board eligible",
                    "advisory council", "advisory committee", "management board", "administration board",
                    "emeritus board", "scientific advisory board", "investment board"]
    r = add_table(ws, r, ["Board-seat exclusions (no level of their own)", "", ""],
                  [[d, "", "Discards the board keyword; the level is recomputed from the remaining keywords (Former Board Member -> Uncategorized)"] for d in excl_display], [40, 22, 100]) + 1

    ws.cell(row=r, column=1, value="Step 3 — Resolve to a single level").font = HEADER_FONT
    r += 1
    for line in SENIORITY_STEP3:
        ws.cell(row=r, column=1, value=line).alignment = WRAP
        r += 1
    print(f"Seniority lexicon rows: {len(lex_rows)}; synonyms: {len(syn_rows)}")
    missing_notes = [" ".join(e.tokens) for e in sen._LEXICON if " ".join(e.tokens) not in SENIORITY_NOTES and " ".join(e.tokens) not in TOKEN_DISPLAY and len(e.tokens) > 1]

    # --- Highlight Mapping (curated, audited against the enum) ---
    ws = wb.create_sheet("Highlight Mapping")
    r = intro(ws, "GDU derives career highlights by combining employment history, organization funding events, organization attributes (e.g. Fortune 500 membership), and job seniority. Each highlight has specific qualification rules; some have CxO/leadership variants that supersede the generic version. A person can earn multiple highlights.")
    with open(ASSETS / "highlights.csv") as f:
        reader = csv.reader(f)
        hl_header = next(reader)
        hl_rows = list(reader)
    documented = {row[0] for row in hl_rows}
    enum_display = {  # enum value -> curated row name
        "FAANG": "FAANG", "Fortune 500 Background": "Fortune 500 Background",
        "VC-backed Experience": "VC-backed Experience", "PE-backed Experience": "PE-backed Experience",
        "PE-backed CxO Experience": "PE-backed CxO Experience",
        "Early-Stage Startup Experience": "Early-Stage Startup Experience",
        "Mid-Stage Startup Experience": "Mid-Stage Startup Experience",
        "[Industry] Veteran": "Industry Veteran", "Company Loyalty": "Company Loyalty",
        "Employee Through [Multiplier] Growth": "Employee Through [#]x Growth",
        "Leadership Through [Multiplier] Growth": "Leadership Through [#]x Growth",
        "Serial Startup Employee": "Serial Startup Employee",
        "CxO During Acquisition": "CxO During Acquisition", "CxO During IPO": "CxO During IPO",
        "Employed During Acquisition": "Employed During Acquisition", "Employed During IPO": "Employed During IPO",
    }
    undocumented = []
    for gv in PersonLayerHighlight.GenericValue:
        name = enum_display.get(gv.value, gv.value)
        if name not in documented:
            undocumented.append(gv.value)
            hl_rows.append([name, gv.value, "", "NOT YET DOCUMENTED — this highlight exists in production but has no reviewed description yet.", "", "", ""])
    add_table(ws, r, hl_header, hl_rows, [30, 30, 24, 60, 50, 50, 50])
    print(f"Highlight rows: {len(hl_rows)} ({len(undocumented)} undocumented: {undocumented})")

    # --- Funding Mapping ---
    ws = wb.create_sheet("Funding Mapping")
    r = intro(ws, "How individual funding round types roll up into the company-stage bands used by the startup-experience highlights.")
    fund_rows = []
    for it in OLFE.InvestmentType:
        stage = OLFE.get_organization_stage(it)
        fund_rows.append([stage.value if stage else "(No Stage Assigned)", it.value.replace("_", " ").title()])
    fund_rows.sort(key=lambda x: (x[0] == "(No Stage Assigned)", x[0]))
    add_table(ws, r, ["Funding Band", "Funding Type"], fund_rows, [28, 32])
    print(f"Funding rows: {len(fund_rows)}")

    wb.save(out_path)
    print(f"\nSaved {out_path}")
    print(f"Code version: {version}")
    if missing_notes:
        print(f"NOTE: multi-word lexicon entries with no note or display mapping: {missing_notes}")
    assert len(ind_rows) > 2000, "industry table suspiciously small"
    assert len(lex_rows) == len(sen._LEXICON), "seniority tab dropped lexicon entries"
    assert len(hl_rows) >= len(list(PersonLayerHighlight.GenericValue)), "highlight tab lost enum coverage"


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "gdu_field_derived_mappings.xlsx")
